/* Reads each Overture places file's footer once and records its spatial
 * extent, so the browser can jump straight to the right file. */
const keys = require('./files.json');
const B = 'https://overturemaps-us-west-2.s3.amazonaws.com/';
const RELEASE = '2026-08-19.0';

(async () => {
  const { parquetMetadataAsync, asyncBufferFromUrl } = await import('hyparquet');
  const out = [];
  for (let i = 0; i < keys.length; i++) {
    const file = await asyncBufferFromUrl({ url: B + keys[i] });
    const meta = await parquetMetadataAsync(file);
    const c0 = meta.row_groups[0].columns;
    const ix = {};
    ['bbox.xmin', 'bbox.xmax', 'bbox.ymin', 'bbox.ymax'].forEach(n => {
      ix[n] = c0.findIndex(c => c.meta_data.path_in_schema.join('.') === n);
    });
    let xmin = Infinity, xmax = -Infinity, ymin = Infinity, ymax = -Infinity;
    for (const g of meta.row_groups) {
      const st = n => g.columns[ix[n]].meta_data.statistics;
      xmin = Math.min(xmin, Number(st('bbox.xmin').min_value));
      xmax = Math.max(xmax, Number(st('bbox.xmax').max_value));
      ymin = Math.min(ymin, Number(st('bbox.ymin').min_value));
      ymax = Math.max(ymax, Number(st('bbox.ymax').max_value));
    }
    const r = v => Math.round(v * 1000) / 1000;
    out.push({ k: keys[i].split('/').pop(), b: [r(xmin), r(ymin), r(xmax), r(ymax)],
      rows: Number(meta.num_rows), groups: meta.row_groups.length,
      size: file.byteLength });
    console.error(`part-${String(i).padStart(5, '0')}  lon [${r(xmin)}, ${r(xmax)}]  lat [${r(ymin)}, ${r(ymax)}]  ${(Number(meta.num_rows) / 1e6).toFixed(2)}M rows`);
  }
  const payload = { release: RELEASE,
    base: B + 'release/' + RELEASE + '/theme=places/type=place/', files: out };
  process.stdout.write('/* Spatial index of the Overture Maps places files for release ' +
    RELEASE + '.\n   Generated by scripts/build-overture-index.js — each entry is the file\'s\n' +
    '   full extent [xmin, ymin, xmax, ymax], used to pick which file to open.\n' +
    '   Overture Maps Foundation data, ODbL / CDLA-Permissive-2.0. */\n' +
    'window.OVERTURE_INDEX = ' + JSON.stringify(payload) + ';\n');
})();
